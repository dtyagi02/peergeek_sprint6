CREATE TABLE public_course_index (
    course_id BIGINT NOT NULL,
    title VARCHAR(120) NOT NULL,
    short_description VARCHAR(300) NULL,
    search_text TEXT NOT NULL COLLATE utf8mb4_0900_ai_ci,
    category_id BIGINT NULL,
    category_name VARCHAR(80) NULL,
    category_slug VARCHAR(100) NULL,
    difficulty VARCHAR(16) NULL,
    topics_text VARCHAR(1000) NULL,
    instructor_id BIGINT NOT NULL,
    instructor_name VARCHAR(120) NULL,
    module_count INT NOT NULL DEFAULT 0,
    lesson_count INT NOT NULL DEFAULT 0,
    thumbnail_resource_id BIGINT NULL,
    published_at TIMESTAMP(6) NOT NULL,
    source_fingerprint CHAR(64) NOT NULL,
    indexed_at TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (course_id),
    INDEX idx_public_course_cat_published (category_id, published_at),
    INDEX idx_public_course_difficulty (difficulty),
    INDEX idx_public_course_published_at (published_at),
    INDEX idx_public_course_title (title(50))
);
